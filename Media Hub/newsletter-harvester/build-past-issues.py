#!/usr/bin/env python3
"""Rebuild past-issues/*.md from the published Digital Lion pages.

Run from anywhere, after a new issue is added to Media Hub/:

    python3 "Media Hub/newsletter-harvester/build-past-issues.py"

It reads every Media Hub/*.html that says "Issue No. N", keeps the English
text only (the .lang-ar spans, scripts, styles and the staff-only mail-out
bar are dropped), and writes one Markdown file per issue. The output is
generated: edit the issue page, not the .md.

No dependencies beyond the standard library.
"""
import html
import os
import re
import subprocess
import sys
from html.parser import HTMLParser

HERE = os.path.dirname(os.path.abspath(__file__))
MEDIA = os.path.dirname(HERE)
OUT = os.path.join(HERE, 'past-issues')

# Elements whose text is never part of the issue a reader sees.
SKIP_TAGS = {'script', 'style', 'noscript', 'svg', 'template'}
SKIP_IDS = {'nl-send', 'copy-toast'}          # sender-only mail bar, clipboard toast
VOID = {'br', 'img', 'meta', 'link', 'input', 'hr', 'source', 'wbr', 'area', 'col', 'embed', 'param', 'track'}
BLOCK = {'p', 'div', 'section', 'article', 'header', 'footer', 'main', 'nav', 'aside',
         'figure', 'figcaption', 'blockquote', 'table', 'tr', 'ul', 'ol', 'br'}


class Extract(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out, self.stack, self.skip = [], [], 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        classes = (a.get('class') or '').split()
        skipping = (tag in SKIP_TAGS or a.get('id') in SKIP_IDS or 'lang-ar' in classes
                    or a.get('lang') == 'ar')
        if tag not in VOID:
            self.stack.append(skipping)
            self.skip += skipping
        if self.skip or skipping:
            return
        if tag in ('h1', 'h2', 'h3', 'h4'):
            self.out.append('\n\n' + '#' * (int(tag[1]) + 1) + ' ')
        elif tag == 'li':
            self.out.append('\n- ')
        elif tag in ('td', 'th'):
            self.out.append(' | ')
        elif tag in BLOCK:
            self.out.append('\n')
        if tag == 'img' and a.get('alt'):
            self.out.append('[image: %s]' % a['alt'])

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        if self.stack:
            self.skip -= self.stack.pop()
        if not self.skip and tag != 'tr' and (tag in BLOCK or tag in ('h1', 'h2', 'h3', 'h4', 'li')):
            self.out.append('\n')

    def handle_data(self, data):
        if not self.skip:
            self.out.append(re.sub(r'\s+', ' ', data))


def text_of(path):
    p = Extract()
    with open(path, encoding='utf-8') as fh:
        p.feed(fh.read())
    t = ''.join(p.out)
    t = re.sub(r'[ \t]+\n', '\n', t)
    t = re.sub(r'\n[ \t]+', '\n', t)
    t = re.sub(r'[ \t]{2,}', ' ', t)
    t = re.sub(r'\n{3,}', '\n\n', t)
    return t.strip()


def year_added(path):
    """Year the page was first committed; issue pages print the day, not the year."""
    try:
        r = subprocess.run(['git', 'log', '--diff-filter=A', '--follow', '--format=%ad',
                            '--date=format:%Y', '--', os.path.basename(path)],
                           cwd=os.path.dirname(path), capture_output=True, text=True, check=True)
        years = r.stdout.split()
        return years[-1] if years else ''
    except (OSError, subprocess.CalledProcessError):
        return ''


def main():
    os.makedirs(OUT, exist_ok=True)
    issues = []
    for name in sorted(os.listdir(MEDIA)):
        if not name.endswith('.html') or name == 'media.html':
            continue
        path = os.path.join(MEDIA, name)
        body = text_of(path)
        m = re.search(r'Issue No\.\s*(\d+)', body)
        if not m:
            continue
        with open(path, encoding='utf-8') as fh:
            title = re.search(r'<title>(.*?)</title>', fh.read(), re.S)
        title = html.unescape(title.group(1)).strip() if title else name
        date = title.split('—')[-1].strip()
        issues.append((int(m.group(1)), name, date, year_added(path), body))

    for no, name, date, year, body in sorted(issues):
        stem = os.path.splitext(name)[0]
        target = os.path.join(OUT, '%02d-%s.md' % (no, stem))
        when = ('%s, %s' % (date, year)) if year else date
        with open(target, 'w', encoding='utf-8') as fh:
            fh.write('# The Digital Lion — Issue No. %d · %s\n\n' % (no, when))
            fh.write('> Source: `Media Hub/%s`. English text only. Generated by '
                     '`build-past-issues.py` — edit the issue page, not this file.\n\n' % name)
            fh.write(body + '\n')
        print('wrote', os.path.relpath(target, os.path.dirname(MEDIA)))
    if not issues:
        sys.exit('no issue pages found in ' + MEDIA)


if __name__ == '__main__':
    main()
